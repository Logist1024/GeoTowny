package com.geotowny.service;

import com.geotowny.config.PluginConfig;
import com.geotowny.core.GeoTownyCore;
import com.geotowny.domain.model.Alliance;
import com.geotowny.domain.model.Ideology;
import com.geotowny.domain.model.Nation;
import com.geotowny.domain.model.NationRank;
import com.geotowny.domain.model.RelationType;
import com.geotowny.domain.model.Resident;
import com.geotowny.domain.model.Town;
import com.geotowny.domain.model.WarState;
import com.geotowny.domain.money.Money;
import com.geotowny.util.Result;

import java.util.HashSet;
import java.util.Set;
import java.util.UUID;

/**
 * 国家领域服务：建国、解散、成员城镇、首都、国王、国库、意识形态、外交与宣战入口。
 * <p>战役/侵略由 P6 的 WarService 接管；P3 只维护外交状态与宣战费用。
 */
public final class NationService {

    private final GeoTownyCore core;
    private final PluginConfig config;

    public NationService(GeoTownyCore core, PluginConfig config) {
        this.core = core;
        this.config = config;
    }

    public Result createNation(Resident founder, Town capital, String name) {
        if (founder == null || capital == null) {
            return Result.fail("城镇或居民不存在。");
        }
        if (!founder.getUuidString().equals(capital.getMayorUuid())
                || !founder.isInTown(capital.getUuid())) {
            return Result.fail("只有城镇市长可以建国。");
        }
        if (capital.hasNation()) {
            return Result.fail("该城镇已属于国家。");
        }
        if (founder.isKing()) {
            return Result.fail("你已是国王，不能创建多个国家。");
        }
        if (!TownService.NAME_PATTERN.matcher(name).matches()) {
            return Result.fail("国家名仅允许中文/英文/数字/下划线，长度 2-24 字符。");
        }
        if (core.getNationByName(name) != null) {
            return Result.fail("国家名已存在。");
        }

        Money cost = Money.of(config.nationCreationCost());
        if (!founder.withdraw(cost)) {
            return Result.fail("建国需 " + cost.format() + " " + config.currencyName() + "，余额不足。");
        }

        Nation nation = new Nation();
        nation.setUuid(UUID.randomUUID().toString());
        nation.setName(name);
        nation.setAutoGeneratedCode(core.generateUniqueNationCode(name));
        nation.setKingUuid(founder.getUuidString());
        nation.setCapitalTownUuid(capital.getUuid());
        nation.setFounded(System.currentTimeMillis());
        nation.setIdeology(Ideology.MONARCHY);
        nation.setColor(0xFFFFFF);
        nation.getTownUuids().add(capital.getUuid());

        capital.setNationUuid(nation.getUuid());
        capital.setCapital(true);
        founder.setNationRank(NationRank.KING);

        core.registerNation(nation);
        core.saveTown(capital);
        core.saveResident(founder);
        return Result.ok("国家 " + name + " 已建立，代码 " + nation.getCode()
                + "。首都为 " + capital.getName() + "。");
    }

    public Result dissolveNation(Resident actor, Nation nation) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以解散国家。");
        }

        Money treasury = nation.getBalance();
        nation.setBalance(Money.ZERO);
        if (treasury.isPositive()) {
            actor.deposit(treasury);
            core.saveResident(actor);
        }

        Set<String> memberTowns = new HashSet<>(nation.getTownUuids());
        for (String townUuid : memberTowns) {
            Town town = core.getTown(townUuid);
            if (town != null) {
                town.setNationUuid(null);
                town.setCapital(false);
                core.saveTown(town);
            }
        }
        nation.getTownUuids().clear();

        clearNationRanks(memberTowns);

        for (Nation other : core.allNations()) {
            if (other != nation && other.getRelations().remove(nation.getUuid()) != null) {
                core.saveNation(other);
            }
        }

        if (nation.getAllianceUuid() != null) {
            Alliance alliance = core.getAlliance(nation.getAllianceUuid());
            if (alliance != null) {
                alliance.getMemberNationUuids().remove(nation.getUuid());
                if (alliance.getMemberNationUuids().isEmpty()) {
                    core.removeAlliance(alliance.getUuid());
                } else if (nation.getUuid().equals(alliance.getLeaderNationUuid())) {
                    alliance.setLeaderNationUuid(alliance.getMemberNationUuids().get(0));
                }
                core.saveAlliances();
            }
        }

        core.unregisterNation(nation);
        return Result.ok("国家 " + nation.getName() + " 已解散，城镇已解除归属。");
    }

    public Result addTown(Resident actor, Nation nation, Town town) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以接纳城镇。");
        }
        if (town == null) {
            return Result.fail("城镇不存在。");
        }
        if (town.hasNation()) {
            return Result.fail("该城镇已属于国家。");
        }
        if (nation.getTownCount() >= config.nationMaxTowns()) {
            return Result.fail("国家成员城镇已达上限 " + config.nationMaxTowns() + "。");
        }

        town.setNationUuid(nation.getUuid());
        town.setCapital(false);
        nation.getTownUuids().add(town.getUuid());
        if (nation.getCapitalTownUuid() == null) {
            nation.setCapitalTownUuid(town.getUuid());
            town.setCapital(true);
        }
        core.saveTown(town);
        core.saveNation(nation);
        return Result.ok("城镇 " + town.getName() + " 已加入国家 " + nation.getName() + "。");
    }

    /**
     * 移除城镇。{@code kingAction=true} 为国王踢出，false 为市长主动退出。
     */
    public Result removeTown(Resident actor, Nation nation, Town town, boolean kingAction) {
        if (nation == null || town == null) {
            return Result.fail("国家或城镇不存在。");
        }
        if (kingAction && !isKing(actor, nation)) {
            return Result.fail("只有国王可以踢出城镇。");
        }
        if (!kingAction && !actor.getUuidString().equals(town.getMayorUuid())) {
            return Result.fail("只有市长可以退出国家。");
        }
        if (!kingAction && !nation.getIdeology().isFreeLeave()) {
            return Result.fail("当前国体不支持自由退出，需国王批准。");
        }
        if (!nation.getUuid().equals(town.getNationUuid())) {
            return Result.fail("该城镇不属于你的国家。");
        }
        if (town.getUuid().equals(nation.getCapitalTownUuid())) {
            return Result.fail("首都不能退出或被踢出，请先变更首都。");
        }

        nation.getTownUuids().remove(town.getUuid());
        town.setNationUuid(null);
        town.setCapital(false);
        clearNationRanks(Set.of(town.getUuid()));
        core.saveTown(town);
        core.saveNation(nation);
        return Result.ok("城镇 " + town.getName() + " 已退出国家 " + nation.getName() + "。");
    }

    public Result setCapital(Resident actor, Nation nation, Town town) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以变更首都。");
        }
        if (town == null || !nation.getUuid().equals(town.getNationUuid())) {
            return Result.fail("该城镇不属于你的国家。");
        }
        if (town.getUuid().equals(nation.getCapitalTownUuid())) {
            return Result.ok("该城镇已经是首都。");
        }
        Town oldCapital = core.getTown(nation.getCapitalTownUuid());
        if (oldCapital != null) {
            oldCapital.setCapital(false);
            core.saveTown(oldCapital);
        }
        nation.setCapitalTownUuid(town.getUuid());
        town.setCapital(true);
        core.saveTown(town);
        core.saveNation(nation);
        return Result.ok("首都已变更为 " + town.getName() + "。");
    }

    public Result setKing(Resident actor, Nation nation, Resident target) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以转让王位。");
        }
        if (target == null) {
            return Result.fail("目标玩家不存在。");
        }
        if (target.getUuidString().equals(actor.getUuidString())) {
            return Result.fail("你已经是国王。");
        }
        Town town = core.getTown(target.getTownUuid());
        if (town == null || !nation.getUuid().equals(town.getNationUuid())) {
            return Result.fail("目标玩家不属于你的国家。");
        }

        actor.setNationRank(NationRank.CITIZEN);
        target.setNationRank(NationRank.KING);
        nation.setKingUuid(target.getUuidString());
        core.saveResident(actor);
        core.saveResident(target);
        core.saveNation(nation);
        return Result.ok("王位已转让给 " + target.getName() + "。");
    }

    public Result setTaxes(Resident actor, Nation nation, Money amount) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以设置国家税。");
        }
        if (amount == null || amount.isNegative()) {
            return Result.fail("税率不能为负数。");
        }
        nation.setTaxes(amount);
        core.saveNation(nation);
        return Result.ok("国家税已设为 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result setBoard(Resident actor, Nation nation, String text) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以修改国家公告。");
        }
        nation.setBoard(text);
        core.saveNation(nation);
        return Result.ok("国家公告已更新。");
    }

    public Result setCode(Resident actor, Nation nation, String code) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以修改国家代码。");
        }
        String normalized = code == null ? "" : code.trim().toUpperCase(java.util.Locale.ROOT);
        if (!normalized.matches("^[A-Z0-9]{4}$")) {
            return Result.fail("国家代码必须是 4 位大写字母或数字。");
        }
        Nation existing = core.getNationByCode(normalized);
        if (existing != null && !existing.getUuid().equals(nation.getUuid())) {
            return Result.fail("该代码已被其他国家使用。");
        }
        String oldCode = nation.getCode();
        nation.setCode(normalized);
        core.updateNationCodeIndex(oldCode, nation);
        core.saveNation(nation);
        return Result.ok("国家代码已设为 " + normalized + "。");
    }

    public Result setIdeology(Resident actor, Nation nation, Ideology ideology) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以变更国体。");
        }
        if (ideology == null) {
            return Result.fail("未知国体。");
        }
        Ideology old = nation.getIdeology();
        if (old == Ideology.THEOCRACY && ideology != Ideology.THEOCRACY) {
            nation.setInfluence(nation.getInfluence() * 0.9);
        }
        nation.setIdeology(ideology);
        core.saveNation(nation);
        String note = isCoreIdeology(ideology) ? "" : "（该意识形态仅保留称呼与数值倍率）";
        return Result.ok("国体已变更为 " + ideology.getDisplayName()
                + (old == Ideology.THEOCRACY && ideology != Ideology.THEOCRACY
                ? "，异端惩罚：影响力 -10%。" : "。") + note);
    }

    private static boolean isCoreIdeology(Ideology ideology) {
        return ideology == Ideology.DEMOCRACY || ideology == Ideology.EMPIRE
                || ideology == Ideology.FEDERATION || ideology == Ideology.THEOCRACY;
    }

    public Result renameNation(Resident actor, Nation nation, String newName) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以改名。");
        }
        if (!TownService.NAME_PATTERN.matcher(newName).matches()) {
            return Result.fail("国家名仅允许中文/英文/数字/下划线，长度 2-24 字符。");
        }
        if (core.getNationByName(newName) != null) {
            return Result.fail("国家名已存在。");
        }
        String oldName = nation.getName();
        String oldCode = nation.getCode();
        boolean autoCode = nation.isCodeAutoGenerated();
        nation.setName(newName);
        core.updateNationNameIndex(oldName, nation);
        if (autoCode) {
            nation.setAutoGeneratedCode(core.generateUniqueNationCode(newName));
            core.updateNationCodeIndex(oldCode, nation);
        }
        core.saveNation(nation);
        return Result.ok("国家已从 " + oldName + " 改名为 " + newName + "。");
    }

    public Result deposit(Resident actor, Nation nation, Money amount) {
        if (nation == null || amount == null || !amount.isPositive()) {
            return Result.fail("金额必须为正数。");
        }
        Town town = core.getTown(actor.getTownUuid());
        if (town == null || !nation.getUuid().equals(town.getNationUuid())) {
            return Result.fail("你不属于该国家。");
        }
        if (!actor.withdraw(amount)) {
            return Result.fail("余额不足。");
        }
        nation.deposit(amount);
        core.saveResident(actor);
        core.saveNation(nation);
        return Result.ok("已向国家国库存入 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result withdraw(Resident actor, Nation nation, Money amount) {
        if (nation == null || amount == null || !amount.isPositive()) {
            return Result.fail("金额必须为正数。");
        }
        if (!isKing(actor, nation) && actor.getNationRank() != NationRank.CHANCELLOR) {
            return Result.fail("只有国王或财相可以取款。");
        }
        if (!nation.withdraw(amount)) {
            return Result.fail("国家国库余额不足。");
        }
        actor.deposit(amount);
        core.saveResident(actor);
        core.saveNation(nation);
        return Result.ok("已从国家国库取出 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result setRelation(Resident actor, Nation nation, Nation target, RelationType type) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以设置外交关系。");
        }
        if (target == null || nation.getUuid().equals(target.getUuid())) {
            return Result.fail("目标国家不存在或不能是自己。");
        }
        if (type == RelationType.AT_WAR) {
            return Result.fail("宣战请使用 /nation war <国家>。");
        }
        if (type == RelationType.VASSAL || type == RelationType.OVERLORD) {
            return Result.fail("附庸关系在 P6 实现。");
        }

        nation.setRelation(target.getUuid(), type);
        target.setRelation(nation.getUuid(), type);
        core.saveNation(nation);
        core.saveNation(target);
        return Result.ok("已与 " + target.getName() + " 建立 " + type.name() + " 关系。");
    }

    public Result declareWar(Resident actor, Nation attacker, Nation defender) {
        if (!isKing(actor, attacker)) {
            return Result.fail("只有国王可以宣战。");
        }
        if (defender == null || attacker.getUuid().equals(defender.getUuid())) {
            return Result.fail("目标国家不存在或不能是自己。");
        }
        if (!config.warEnabled()) {
            return Result.fail("战争系统已禁用。");
        }
        if (attacker.getRelation(defender.getUuid()) == RelationType.AT_WAR) {
            return Result.fail("你们已处于战争状态。");
        }
        Money cost = Money.of(config.warDeclareCost());
        if (!attacker.withdraw(cost)) {
            return Result.fail("国家国库不足支付宣战费 " + cost.format() + "。");
        }
        attacker.setRelation(defender.getUuid(), RelationType.AT_WAR);
        defender.setRelation(attacker.getUuid(), RelationType.AT_WAR);
        attacker.setWarState(WarState.ACTIVE);
        defender.setWarState(WarState.ACTIVE);
        core.saveNation(attacker);
        core.saveNation(defender);
        return Result.ok("已向 " + defender.getName() + " 宣战。战役与占领系统在 P6 接入。");
    }

    public Result makePeace(Resident actor, Nation nation, Nation target) {
        if (!isKing(actor, nation)) {
            return Result.fail("只有国王可以议和。");
        }
        if (target == null || nation.getUuid().equals(target.getUuid())) {
            return Result.fail("目标国家不存在。");
        }
        if (nation.getRelation(target.getUuid()) != RelationType.AT_WAR) {
            return Result.fail("你们并未处于战争状态。");
        }
        nation.setRelation(target.getUuid(), RelationType.NEUTRAL);
        target.setRelation(nation.getUuid(), RelationType.NEUTRAL);
        nation.setWarState(WarState.ENDED);
        target.setWarState(WarState.ENDED);
        core.saveNation(nation);
        core.saveNation(target);
        return Result.ok("已与 " + target.getName() + " 停战。");
    }

    public boolean isKing(Resident resident, Nation nation) {
        return resident != null && nation != null
                && nation.getKingUuid() != null
                && nation.getKingUuid().equals(resident.getUuidString());
    }

    private void clearNationRanks(Set<String> memberTowns) {
        for (Resident resident : core.allResidents()) {
            if (resident.getTownUuid() != null && memberTowns.contains(resident.getTownUuid())
                    && resident.getNationRank() != null) {
                resident.setNationRank(null);
                core.saveResident(resident);
            }
        }
    }
}