/**
 * 城镇领域服务：建城、解散、改名、成员、国库、设置。
 * <p>所有写操作通过本服务完成，命令层只做参数解析与消息展示。
 */
public final class TownService {

    public static final Pattern NAME_PATTERN = Pattern.compile("^[\\p{IsHan}A-Za-z0-9_]{2,24}$");

    private final GeoTownyCore core;
    private final PluginConfig config;

    public TownService(GeoTownyCore core, PluginConfig config) {
        this.core = core;
        this.config = config;
    }

    public Result createTown(Resident mayor, String name, String worldKey,
                             int chunkX, int chunkZ, WorldLocation spawn) {
        if (mayor == null) {
            return Result.fail("居民数据不存在。");
        }
        if (mayor.hasTown()) {
            Town current = core.getTown(mayor.getTownUuid());
            return Result.fail("你已属于城镇 " + (current == null ? "?" : current.getName())
                    + "，请先离开后再创建新城镇。");
        }
        if (!NAME_PATTERN.matcher(name).matches()) {
            return Result.fail("城镇名仅允许中文/英文/数字/下划线，长度 2-24 字符。");
        }
        if (core.getTownByName(name) != null) {
            return Result.fail("城镇名已存在。");
        }
        if ("minecraft:the_nether".equals(worldKey) || "minecraft:the_end".equals(worldKey)) {
            return Result.fail("禁止在下界和末地创建城镇。");
        }
        if (core.getTownBlockAt(worldKey, chunkX, chunkZ) != null) {
            return Result.fail("当前区块已被其他城镇占领。");
        }

        Money cost = Money.of(config.townCreationCost());
        if (!mayor.withdraw(cost)) {
            return Result.fail("创建城镇需 " + cost.format() + " " + config.currencyName() + "，余额不足。");
        }

        Town town = new Town();
        town.setUuid(UUID.randomUUID().toString());
        town.setName(name);
        town.setMayorUuid(mayor.getUuidString());
        town.setFounded(System.currentTimeMillis());
        town.setBalance(cost);
        town.setTaxes(Money.ZERO);
        town.setPlotPrice(Money.ZERO);
        town.setColor(0xFFFFFF);
        town.setAutoGeneratedCode(core.generateUniqueTownCode(name));
        town.getResidentUuids().add(mayor.getUuidString());

        TownBlock home = new TownBlock(worldKey, chunkX, chunkZ, town.getUuid());
        town.getClaimBlockKeys().add(home.key());
        town.setHomeBlockKey(home.key());
        town.setSpawn(spawn);

        mayor.joinTown(town.getUuid());
        mayor.setTownRank(TownRank.MAYOR);

        core.registerTown(town);
        core.putTownBlock(home);
        core.saveTownBlocks();
        core.saveResident(mayor);

        return Result.ok("城镇 " + name + " 已建立，代码 " + town.getCode()
                + "。你是市长，当前区块已设为城镇中心。");
    }

    public Result deleteTown(Resident actor, Town town) {
        if (town == null) {
            return Result.fail("城镇不存在。");
        }
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以解散城镇。");
        }

        return dissolveTown(town);
    }

    /**
     * 系统解散：不校验操作者，供破产与废弃清理调用。
     */
    public Result dissolveTown(Town town) {
        if (town == null) {
            return Result.fail("城镇不存在。");
        }
        // D-04：国库退还市长；无市长则归国家，否则销毁。
        Money remaining = town.getBalance();
        town.setBalance(Money.ZERO);
        Resident mayor = core.getResident(town.getMayorUuid());
        if (remaining.isPositive()) {
            if (mayor != null) {
                mayor.deposit(remaining);
                core.saveResident(mayor);
            } else if (town.hasNation()) {
                Nation nation = core.getNation(town.getNationUuid());
                if (nation != null) {
                    nation.deposit(remaining);
                    core.saveNation(nation);
                }
            }
        }

        // 释放领地
        for (String key : new ArrayList<>(town.getClaimBlockKeys())) {
            core.removeTownBlock(key);
        }
        town.getClaimBlockKeys().clear();

        // 移除居民归属
        for (String residentUuid : new ArrayList<>(town.getResidentUuids())) {
            Resident resident = core.getResident(residentUuid);
            if (resident == null) {
                continue;
            }
            resident.leaveTown();
            core.saveResident(resident);
        }
        town.getResidentUuids().clear();

        // 从国家剔除并处理首都
        if (town.hasNation()) {
            Nation nation = core.getNation(town.getNationUuid());
            if (nation != null) {
                nation.getTownUuids().remove(town.getUuid());
                nation.getProvinceTowns().remove(town.getUuid());
                if (town.getUuid().equals(nation.getCapitalTownUuid())) {
                    nation.setCapitalTownUuid(null);
                    for (String candidateUuid : nation.getTownUuids()) {
                        Town candidate = core.getTown(candidateUuid);
                        if (candidate != null) {
                            candidate.setCapital(true);
                            nation.setCapitalTownUuid(candidateUuid);
                            core.saveTown(candidate);
                            break;
                        }
                    }
                }
                if (nation.getCapitalTownUuid() == null) {
                    Resident king = core.getResident(nation.getKingUuid());
                    if (king != null) {
                        king.setNationRank(null);
                        core.saveResident(king);
                    }
                    core.unregisterNation(nation);
                } else {
                    core.saveNation(nation);
                }
            }
        }

        town.setCapital(false);
        core.unregisterTown(town);
        core.saveTownBlocks();
        return Result.ok("城镇 " + town.getName() + " 已解散，领地已释放。");
    }

    /**
     * 城镇合并：源城镇的资金、领地、居民并入目标城镇，源城镇删除。
     * <p>P3 简化版：不迁移源城镇的国家首都身份；若源城镇是首都，从原国家移除并按规则选新首都。
     */
    public Result mergeTowns(Resident actor, Town source, Town target) {
        if (!isMayor(actor, source)) {
            return Result.fail("只有源城镇市长可以发起合并。");
        }
        if (target == null) {
            return Result.fail("目标城镇不存在。");
        }
        if (source.getUuid().equals(target.getUuid())) {
            return Result.fail("不能与自己合并。");
        }

        Money amount = source.getBalance();
        source.setBalance(Money.ZERO);
        target.deposit(amount);

        for (String key : new ArrayList<>(source.getClaimBlockKeys())) {
            TownBlock block = core.getTownBlock(key);
            if (block != null) {
                block.setTownUuid(target.getUuid());
                target.getClaimBlockKeys().add(key);
            }
        }
        source.getClaimBlockKeys().clear();

        for (String residentUuid : new ArrayList<>(source.getResidentUuids())) {
            Resident resident = core.getResident(residentUuid);
            if (resident == null) {
                continue;
            }
            resident.leaveTown();
            resident.joinTown(target.getUuid());
            resident.setTownRank(TownRank.RESIDENT);
            target.addResident(residentUuid);
            core.saveResident(resident);
        }
        source.getResidentUuids().clear();

        if (source.hasNation()) {
            Nation nation = core.getNation(source.getNationUuid());
            if (nation != null) {
                nation.getTownUuids().remove(source.getUuid());
                nation.getProvinceTowns().remove(source.getUuid());
                if (source.getUuid().equals(nation.getCapitalTownUuid())) {
                    nation.setCapitalTownUuid(null);
                    for (String candidateUuid : nation.getTownUuids()) {
                        Town candidate = core.getTown(candidateUuid);
                        if (candidate != null) {
                            candidate.setCapital(true);
                            nation.setCapitalTownUuid(candidateUuid);
                            core.saveTown(candidate);
                            break;
                        }
                    }
                }
                if (nation.getCapitalTownUuid() == null) {
                    Resident king = core.getResident(nation.getKingUuid());
                    if (king != null) {
                        king.setNationRank(null);
                        core.saveResident(king);
                    }
                    core.unregisterNation(nation);
                } else {
                    core.saveNation(nation);
                }
            }
        }

        source.setCapital(false);
        core.unregisterTown(source);
        core.saveTown(target);
        core.saveTownBlocks();
        return Result.ok("城镇 " + source.getName() + " 已并入 " + target.getName() + "。");
    }

    /**
     * 城镇分裂：市长把当前区块及自身分出去，建立新城镇。
     * <p>启动资金从原城镇国库转入，最多不超过建城费，保证资金守恒。
     */
    public Result splitTown(Resident actor, Town town, String newName,
                            String worldKey, int chunkX, int chunkZ, WorldLocation spawn) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以分裂城镇。");
        }
        if (!NAME_PATTERN.matcher(newName).matches()) {
            return Result.fail("城镇名仅允许中文/英文/数字/下划线，长度 2-24 字符。");
        }
        if (core.getTownByName(newName) != null) {
            return Result.fail("城镇名已存在。");
        }
        String key = TownBlock.keyOf(worldKey, chunkX, chunkZ);
        TownBlock block = core.getTownBlock(key);
        if (block == null || !town.getUuid().equals(block.getTownUuid())) {
            return Result.fail("当前区块不属于你的城镇。");
        }
        if (key.equals(town.getHomeBlockKey())) {
            return Result.fail("不可分裂城镇中心地块，请移动到其他区块。");
        }

        Money maxSeed = Money.of(config.townCreationCost());
        Money seed = town.getBalance().compareTo(maxSeed) <= 0 ? town.getBalance() : maxSeed;
        town.withdraw(seed);

        Town newTown = new Town();
        newTown.setUuid(UUID.randomUUID().toString());
        newTown.setName(newName);
        newTown.setMayorUuid(actor.getUuidString());
        newTown.setFounded(System.currentTimeMillis());
        newTown.setBalance(seed);
        newTown.setTaxes(Money.ZERO);
        newTown.setPlotPrice(Money.ZERO);
        newTown.setColor(0xFFFFFF);
        newTown.setAutoGeneratedCode(core.generateUniqueTownCode(newName));
        newTown.getResidentUuids().add(actor.getUuidString());
        newTown.getClaimBlockKeys().add(key);
        newTown.setHomeBlockKey(key);
        newTown.setSpawn(spawn);

        block.setTownUuid(newTown.getUuid());
        town.getClaimBlockKeys().remove(key);
        town.getResidentUuids().remove(actor.getUuidString());
        actor.leaveTown();
        actor.joinTown(newTown.getUuid());
        actor.setTownRank(TownRank.MAYOR);

        core.registerTown(newTown);
        if (town.getResidentUuids().isEmpty()) {
            town.setMayorUuid(null);
        }
        core.saveTown(town);
        core.saveTownBlocks();
        core.saveResident(actor);
        return Result.ok("城镇 " + newName + " 已从 " + town.getName()
                + " 分裂，你是新城镇市长，启动资金 " + seed.format() + "。");
    }

    public Result renameTown(Resident actor, Town town, String newName) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以改名。");
        }
        if (!NAME_PATTERN.matcher(newName).matches()) {
            return Result.fail("城镇名仅允许中文/英文/数字/下划线，长度 2-24 字符。");
        }
        if (core.getTownByName(newName) != null) {
            return Result.fail("城镇名已存在。");
        }

        String oldName = town.getName();
        String oldCode = town.getCode();
        boolean autoCode = town.isCodeAutoGenerated();

        town.setName(newName);
        core.updateTownNameIndex(oldName, town);
        if (autoCode) {
            town.setAutoGeneratedCode(core.generateUniqueTownCode(newName));
            core.updateTownCodeIndex(oldCode, town);
        }
        core.saveTown(town);
        return Result.ok("城镇已从 " + oldName + " 改名为 " + newName
                + (autoCode ? "，代码更新为 " + town.getCode() : "") + "。");
    }

    public Result joinTown(Resident target, Town town, boolean requireOpen) {
        if (target == null || town == null) {
            return Result.fail("城镇或居民不存在。");
        }
        if (target.isInTown(town.getUuid())) {
            return Result.fail("你已在该城镇中。");
        }
        if (target.hasTown()) {
            Town current = core.getTown(target.getTownUuid());
            return Result.fail("你已属于城镇 " + (current == null ? "?" : current.getName())
                    + "，请先离开当前城镇。");
        }
        if (requireOpen && !town.isOpen()) {
            return Result.fail("该城镇未开放加入，需市长邀请。");
        }

        target.joinTown(town.getUuid());
        target.setTownRank(TownRank.RESIDENT);
        town.addResident(target.getUuidString());
        core.saveResident(target);
        core.saveTown(town);
        return Result.ok("你已加入城镇 " + town.getName() + "。");
    }

    public Result leaveTown(Resident target, Town town) {
        if (target == null || town == null || !target.isInTown(town.getUuid())) {
            return Result.fail("你不在该城镇中。");
        }
        if (target.getUuidString().equals(town.getMayorUuid())) {
            return Result.fail("市长不能直接离开，请先用 /town set mayor 转让。");
        }
        town.removeResident(target.getUuidString());
        target.leaveTown();
        core.saveResident(target);
        core.saveTown(town);
        return Result.ok("你已离开城镇 " + town.getName() + "。");
    }

    public Result kickMember(Resident actor, Town town, Resident target) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以踢出成员。");
        }
        if (target == null || !target.isInTown(town.getUuid())) {
            return Result.fail("该玩家不在你的城镇。");
        }
        if (target.getUuidString().equals(town.getMayorUuid())) {
            return Result.fail("不能踢出市长。");
        }
        town.removeResident(target.getUuidString());
        target.leaveTown();
        core.saveResident(target);
        core.saveTown(town);
        return Result.ok(target.getName() + " 已被踢出城镇。");
    }

    public Result setMayor(Resident actor, Town town, Resident target) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以转让职位。");
        }
        if (target == null || !target.isInTown(town.getUuid())) {
            return Result.fail("该玩家不在你的城镇。");
        }
        if (target.getUuidString().equals(actor.getUuidString())) {
            return Result.fail("你已经是市长。");
        }

        actor.setTownRank(TownRank.RESIDENT);
        target.setTownRank(TownRank.MAYOR);
        town.setMayorUuid(target.getUuidString());

        if (town.hasNation() && town.isCapital()) {
            Nation nation = core.getNation(town.getNationUuid());
            if (nation != null) {
                actor.setNationRank(NationRank.CITIZEN);
                target.setNationRank(NationRank.KING);
                nation.setKingUuid(target.getUuidString());
                core.saveNation(nation);
            }
        }

        core.saveResident(actor);
        core.saveResident(target);
        core.saveTown(town);
        return Result.ok("市长已转让给 " + target.getName() + "。");
    }

    public Result deposit(Resident actor, Town town, Money amount) {
        if (!actor.isInTown(town.getUuid())) {
            return Result.fail("你不在该城镇中。");
        }
        if (amount == null || !amount.isPositive()) {
            return Result.fail("金额必须为正数。");
        }
        if (!actor.withdraw(amount)) {
            return Result.fail("余额不足。");
        }
        town.deposit(amount);
        core.saveResident(actor);
        core.saveTown(town);
        return Result.ok("已向城镇国库存入 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result withdraw(Resident actor, Town town, Money amount) {
        if (!isMayor(actor, town) && actor.getTownRank() != TownRank.TREASURER) {
            return Result.fail("只有市长或财务可以取款。");
        }
        if (amount == null || !amount.isPositive()) {
            return Result.fail("金额必须为正数。");
        }
        if (!town.withdraw(amount)) {
            return Result.fail("城镇国库余额不足。");
        }
        actor.deposit(amount);
        core.saveResident(actor);
        core.saveTown(town);
        return Result.ok("已从城镇国库取出 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result setTaxes(Resident actor, Town town, Money amount) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以设置税收。");
        }
        if (amount == null || amount.isNegative()) {
            return Result.fail("税收不能为负数。");
        }
        town.setTaxes(amount);
        core.saveTown(town);
        return Result.ok("居民税已设为 " + amount.format() + " " + config.currencyName() + "。");
    }

    public Result setBoard(Resident actor, Town town, String text) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以修改公告。");
        }
        town.setBoard(text);
        core.saveTown(town);
        return Result.ok("城镇公告已更新。");
    }

    public Result setOpen(Resident actor, Town town, boolean open) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以修改加入设置。");
        }
        town.setOpen(open);
        core.saveTown(town);
        return Result.ok(open ? "城镇已开放任意加入。" : "城镇已关闭开放加入。");
    }

    public Result setPublic(Resident actor, Town town, boolean isPublic) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以修改出生点可见性。");
        }
        town.setPublic(isPublic);
        core.saveTown(town);
        return Result.ok(isPublic ? "城镇出生点已公开。" : "城镇出生点已设为私有。");
    }

    public Result setCode(Resident actor, Town town, String code) {
        if (!isMayor(actor, town)) {
            return Result.fail("只有市长可以修改城镇代码。");
        }
        String normalized = code == null ? "" : code.trim().toUpperCase(LocaleHolder.LOCALE);
        if (!normalized.matches("^[A-Z0-9]{3}$")) {
            return Result.fail("城镇代码必须是 3 位大写字母或数字。");
        }
        Town existing = core.getTownByCode(normalized);
        if (existing != null && !existing.getUuid().equals(town.getUuid())) {
            return Result.fail("该代码已被其他城镇使用。");
        }
        String oldCode = town.getCode();
        town.setCode(normalized);
        core.updateTownCodeIndex(oldCode, town);
        core.saveTown(town);
        return Result.ok("城镇代码已设为 " + normalized + "。");
    }

    public boolean isMayor(Resident resident, Town town) {
        return resident != null && town != null
                && resident.getUuidString().equals(town.getMayorUuid())
                && resident.isInTown(town.getUuid());
    }

    public List<Town> townsOf(Resident resident) {
        Town town = resident == null ? null : core.getTown(resident.getTownUuid());
        return town == null ? List.of() : List.of(town);
    }

    private static final class LocaleHolder {
        private static final java.util.Locale LOCALE = java.util.Locale.ROOT;
    }
}