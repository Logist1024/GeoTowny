package com.geotowny.domain.model;

import com.geotowny.domain.money.Money;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

/**
 * 城镇聚合根。
 * <p>金额统一使用 {@link Money}；居民与领地的 UUID 列表是本聚合内的索引，
 * 跨聚合只引用 ID。
 */
public class Town {

    private String uuid;
    private String name;
    private String code;
    private boolean codeAutoGenerated = true;
    private String mayorUuid;
    private String nationUuid;
    private List<String> residentUuids = new ArrayList<>();
    private List<String> claimBlockKeys = new CopyOnWriteArrayList<>();
    private String homeBlockKey;
    private WorldLocation spawn;
    private Money balance = Money.ZERO;
    private Money taxes = Money.ZERO;
    private Money plotPrice = Money.ZERO;
    private long founded;
    private boolean open;
    private boolean isPublic;
    private boolean pvpEnabled;
    private String board;

    private boolean isCapital;
    private double influence;
    private int fortificationLevel;
    private int color;

    private long lastActiveTime;
    private boolean abandoned;
    private long abandonedSince;

    private boolean borderEnabled = true;
    private int borderColor;
    private int borderHeight;
    private double borderParticleInterval = 1.0d;

    private static final double[] ALLOWED_INTERVALS = {0.1d, 0.3d, 0.5d, 0.6d, 0.8d, 1.0d};

    private int bankruptcyDays;
    private long bankruptcySince;

    public Town() {
    }

    public String getUuid() {
        return uuid;
    }

    public void setUuid(String uuid) {
        this.uuid = uuid;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
        this.codeAutoGenerated = false;
    }

    public boolean isCodeAutoGenerated() {
        return codeAutoGenerated;
    }

    public void setAutoGeneratedCode(String code) {
        this.code = code;
        this.codeAutoGenerated = true;
    }

    public String getMayorUuid() {
        return mayorUuid;
    }

    public void setMayorUuid(String mayorUuid) {
        this.mayorUuid = mayorUuid;
    }

    public String getNationUuid() {
        return nationUuid;
    }

    public void setNationUuid(String nationUuid) {
        this.nationUuid = nationUuid;
    }

    public boolean hasNation() {
        return nationUuid != null && !nationUuid.isEmpty();
    }

    public List<String> getResidentUuids() {
        return residentUuids;
    }

    public void addResident(String uuid) {
        if (!residentUuids.contains(uuid)) {
            residentUuids.add(uuid);
        }
    }

    public void removeResident(String uuid) {
        residentUuids.remove(uuid);
    }

    public List<String> getClaimBlockKeys() {
        return claimBlockKeys;
    }

    public String getHomeBlockKey() {
        return homeBlockKey;
    }

    public void setHomeBlockKey(String key) {
        this.homeBlockKey = key;
    }

    public WorldLocation getSpawn() {
        return spawn;
    }

    public void setSpawn(WorldLocation spawn) {
        this.spawn = spawn;
    }

    public Money getBalance() {
        return balance == null ? Money.ZERO : balance;
    }

    public void setBalance(Money balance) {
        this.balance = balance == null ? Money.ZERO : balance;
    }

    public void deposit(Money amount) {
        if (amount != null && amount.isPositive()) {
            this.balance = getBalance().plus(amount);
        }
    }

    public boolean withdraw(Money amount) {
        if (amount == null || !amount.isPositive() || getBalance().compareTo(amount) < 0) {
            return false;
        }
        this.balance = getBalance().minus(amount);
        return true;
    }

    public Money getTaxes() {
        return taxes == null ? Money.ZERO : taxes;
    }

    public void setTaxes(Money taxes) {
        this.taxes = taxes == null ? Money.ZERO : taxes;
    }

    public Money getPlotPrice() {
        return plotPrice == null ? Money.ZERO : plotPrice;
    }

    public void setPlotPrice(Money price) {
        this.plotPrice = price == null ? Money.ZERO : price;
    }

    public long getFounded() {
        return founded;
    }

    public void setFounded(long founded) {
        this.founded = founded;
    }

    public boolean isOpen() {
        return open;
    }

    public void setOpen(boolean open) {
        this.open = open;
    }

    public boolean isPublic() {
        return isPublic;
    }

    public void setPublic(boolean aPublic) {
        this.isPublic = aPublic;
    }

    public boolean isPvpEnabled() {
        return pvpEnabled;
    }

    public void setPvpEnabled(boolean pvpEnabled) {
        this.pvpEnabled = pvpEnabled;
    }

    public String getBoard() {
        return board;
    }

    public void setBoard(String board) {
        this.board = board;
    }

    public boolean isCapital() {
        return isCapital;
    }

    public void setCapital(boolean capital) {
        this.isCapital = capital;
    }

    public double getInfluence() {
        return influence;
    }

    public void setInfluence(double influence) {
        this.influence = influence;
    }

    public void addInfluence(double amount) {
        this.influence += amount;
    }

    public int getFortificationLevel() {
        return fortificationLevel;
    }

    public void setFortificationLevel(int level) {
        this.fortificationLevel = level;
    }

    public int getColor() {
        return color;
    }

    public void setColor(int color) {
        this.color = color;
    }

    public int getResidentCount() {
        return residentUuids.size();
    }

    public int getClaimCount() {
        return claimBlockKeys.size();
    }

    public long getLastActiveTime() {
        return lastActiveTime;
    }

    public void setLastActiveTime(long t) {
        this.lastActiveTime = t;
    }

    public boolean isAbandoned() {
        return abandoned;
    }

    public void setAbandoned(boolean abandoned) {
        this.abandoned = abandoned;
    }

    public long getAbandonedSince() {
        return abandonedSince;
    }

    public void setAbandonedSince(long t) {
        this.abandonedSince = t;
    }

    public int getBankruptcyDays() {
        return bankruptcyDays;
    }

    public void setBankruptcyDays(int days) {
        this.bankruptcyDays = days;
    }

    public long getBankruptcySince() {
        return bankruptcySince;
    }

    public void setBankruptcySince(long t) {
        this.bankruptcySince = t;
    }

    public boolean isBorderEnabled() {
        return borderEnabled;
    }

    public void setBorderEnabled(boolean borderEnabled) {
        this.borderEnabled = borderEnabled;
    }

    public int getBorderColor() {
        return borderColor;
    }

    public void setBorderColor(int borderColor) {
        this.borderColor = borderColor;
    }

    public int getEffectiveBorderColor() {
        return borderColor != 0 ? borderColor : color;
    }

    public int getBorderHeight() {
        return borderHeight;
    }

    public void setBorderHeight(int borderHeight) {
        this.borderHeight = borderHeight;
    }

    public double getBorderParticleInterval() {
        return borderParticleInterval;
    }

    public void setBorderParticleInterval(double value) {
        if (!Double.isFinite(value) || value <= 0) {
            this.borderParticleInterval = 1.0d;
            return;
        }
        double best = ALLOWED_INTERVALS[0];
        double bestDiff = Math.abs(value - best);
        for (double allowed : ALLOWED_INTERVALS) {
            double diff = Math.abs(value - allowed);
            if (diff < bestDiff) {
                bestDiff = diff;
                best = allowed;
            }
        }
        this.borderParticleInterval = best;
    }

    public static double[] getAllowedIntervals() {
        return ALLOWED_INTERVALS.clone();
    }
}