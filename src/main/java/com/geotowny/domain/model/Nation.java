package com.geotowny.domain.model;

import com.geotowny.domain.money.Money;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * 国家聚合根。
 * <p>按决策 D-03/D-05 收敛：攻城状态迁移到 P6 的 {@code Campaign}；
 * 删除神谕、刺激金、公共仓库、骑士、议会否决等未接线机制。
 */
public class Nation {

    private String uuid;
    private String name;
    private String code;
    private boolean codeAutoGenerated = true;
    private String kingUuid;
    private String capitalTownUuid;
    private List<String> townUuids = new ArrayList<>();
    private Money balance = Money.ZERO;
    private Money taxes = Money.ZERO;
    private long founded;
    private String board;

    private Ideology ideology = Ideology.MONARCHY;
    private int color;
    private double influence;
    private int techLevel;
    private double stability;
    private String flag;

    private Map<String, RelationType> relations = new HashMap<>();
    private WarState warState = WarState.NONE;

    private long termStart;
    private long termDuration = 30L * 24 * 60 * 60 * 1000;

    /** 宣战公投：目标国家 uuid -> {赞成票数, 反对票数, 截止时间戳} */
    private Map<String, long[]> warVotes = new HashMap<>();
    /** 弹劾投票：[发起时间戳, 赞成票数, 反对票数] */
    private long[] impeachmentVote;

    /** 行省城镇（帝国制） */
    private List<String> provinceTowns = new ArrayList<>();

    /** 神职人员（神权制）：玩家 uuid -> 神职名 */
    private Map<String, String> clergy = new HashMap<>();

    private boolean exiled;
    private long exileSince;
    private long exileUntil;
    private String exiledName;
    private List<String> exileMembers = new ArrayList<>();
    private Ideology exileIdeology;

    private String allianceUuid;

    public Nation() {
    }

    public String getUuid() {
        return uuid;
    }

    public void setUuid(String uuid) {
        this.uuid = uuid;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
        this.codeAutoGenerated = false;
    }

    public boolean isCodeAutoGenerated() {
        return codeAutoGenerated;
    }

    public void setAutoGeneratedCode(String code) {
        this.code = code;
        this.codeAutoGenerated = true;
    }

    public String getKingUuid() {
        return kingUuid;
    }

    public void setKingUuid(String kingUuid) {
        this.kingUuid = kingUuid;
    }

    public String getCapitalTownUuid() {
        return capitalTownUuid;
    }

    public void setCapitalTownUuid(String capitalTownUuid) {
        this.capitalTownUuid = capitalTownUuid;
    }

    public List<String> getTownUuids() {
        return townUuids;
    }

    public Money getBalance() {
        return balance == null ? Money.ZERO : balance;
    }

    public void setBalance(Money balance) {
        this.balance = balance == null ? Money.ZERO : balance;
    }

    public void deposit(Money amount) {
        if (amount != null && amount.isPositive()) {
            this.balance = getBalance().plus(amount);
        }
    }

    public boolean withdraw(Money amount) {
        if (amount == null || !amount.isPositive() || getBalance().compareTo(amount) < 0) {
            return false;
        }
        this.balance = getBalance().minus(amount);
        return true;
    }

    public Money getTaxes() {
        return taxes == null ? Money.ZERO : taxes;
    }

    public void setTaxes(Money taxes) {
        this.taxes = taxes == null ? Money.ZERO : taxes;
    }

    public long getFounded() {
        return founded;
    }

    public void setFounded(long founded) {
        this.founded = founded;
    }

    public String getBoard() {
        return board;
    }

    public void setBoard(String board) {
        this.board = board;
    }

    public Ideology getIdeology() {
        return ideology == null ? Ideology.MONARCHY : ideology;
    }

    public void setIdeology(Ideology ideology) {
        this.ideology = ideology == null ? Ideology.MONARCHY : ideology;
    }

    public int getColor() {
        return color;
    }

    public void setColor(int color) {
        this.color = color;
    }

    public double getInfluence() {
        return influence;
    }

    public void setInfluence(double influence) {
        this.influence = influence;
    }

    public void addInfluence(double amount) {
        this.influence += amount;
    }

    public int getTechLevel() {
        return techLevel;
    }

    public void setTechLevel(int techLevel) {
        this.techLevel = techLevel;
    }

    public double getStability() {
        return stability;
    }

    public void setStability(double stability) {
        this.stability = Math.max(0, Math.min(100, stability));
    }

    public String getFlag() {
        return flag;
    }

    public void setFlag(String flag) {
        this.flag = flag;
    }

    public Map<String, RelationType> getRelations() {
        if (relations == null) {
            relations = new HashMap<>();
        }
        return relations;
    }

    public RelationType getRelation(String otherNationUuid) {
        return getRelations().getOrDefault(otherNationUuid, RelationType.NEUTRAL);
    }

    public void setRelation(String otherNationUuid, RelationType type) {
        if (type == RelationType.NEUTRAL) {
            getRelations().remove(otherNationUuid);
        } else {
            getRelations().put(otherNationUuid, type);
        }
    }

    public WarState getWarState() {
        return warState == null ? WarState.NONE : warState;
    }

    public void setWarState(WarState warState) {
        this.warState = warState == null ? WarState.NONE : warState;
    }

    public int getTownCount() {
        return townUuids.size();
    }

    public long getTermStart() {
        return termStart;
    }

    public void setTermStart(long termStart) {
        this.termStart = termStart;
    }

    public long getTermDuration() {
        return termDuration;
    }

    public void setTermDuration(long termDuration) {
        this.termDuration = termDuration;
    }

    public Map<String, long[]> getWarVotes() {
        if (warVotes == null) {
            warVotes = new HashMap<>();
        }
        return warVotes;
    }

    public long[] getImpeachmentVote() {
        return impeachmentVote;
    }

    public void setImpeachmentVote(long[] vote) {
        this.impeachmentVote = vote;
    }

    public List<String> getProvinceTowns() {
        if (provinceTowns == null) {
            provinceTowns = new ArrayList<>();
        }
        return provinceTowns;
    }

    public boolean isProvinceTown(String townUuid) {
        return provinceTowns != null && provinceTowns.contains(townUuid);
    }

    public Map<String, String> getClergy() {
        if (clergy == null) {
            clergy = new HashMap<>();
        }
        return clergy;
    }

    public boolean isExiled() {
        return exiled;
    }

    public void setExiled(boolean exiled) {
        this.exiled = exiled;
    }

    public long getExileSince() {
        return exileSince;
    }

    public void setExileSince(long t) {
        this.exileSince = t;
    }

    public long getExileUntil() {
        return exileUntil;
    }

    public void setExileUntil(long t) {
        this.exileUntil = t;
    }

    public String getExiledName() {
        return exiledName;
    }

    public void setExiledName(String exiledName) {
        this.exiledName = exiledName;
    }

    public List<String> getExileMembers() {
        if (exileMembers == null) {
            exileMembers = new ArrayList<>();
        }
        return exileMembers;
    }

    public Ideology getExileIdeology() {
        return exileIdeology;
    }

    public void setExileIdeology(Ideology ideology) {
        this.exileIdeology = ideology;
    }

    public String getAllianceUuid() {
        return allianceUuid;
    }

    public void setAllianceUuid(String uuid) {
        this.allianceUuid = uuid;
    }

    public boolean hasAlliance() {
        return allianceUuid != null && !allianceUuid.isEmpty();
    }
}