package com.geotowny.core;

import com.geotowny.config.PluginConfig;
import com.geotowny.domain.model.Town;
import com.geotowny.storage.StorageService;
import org.bukkit.configuration.file.YamlConfiguration;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Path;

import static org.assertj.core.api.Assertions.assertThat;

class GeoTownyCoreTest {

    @TempDir
    Path tempDir;

    private StorageService storage;
    private GeoTownyCore core;

    @BeforeEach
    void setUp() {
        storage = new StorageService(tempDir.resolve("plugin"));
        storage.start();
        core = new GeoTownyCore(storage, new PluginConfig(new YamlConfiguration()));
        core.load();
    }

    @AfterEach
    void tearDown() {
        storage.close();
    }

    @Test
    void generatesThreeCharacterUniqueTownCode() {
        String code = core.generateUniqueTownCode("柏林");

        assertThat(code).hasSize(3);
        assertThat(code).matches("[A-Z0-9]{3}");
    }

    @Test
    void avoidsCodeCollision() {
        Town first = new Town();
        first.setUuid("t1");
        first.setName("A城");
        first.setAutoGeneratedCode(core.generateUniqueTownCode("柏林"));
        core.registerTown(first);

        String second = core.generateUniqueTownCode("柏林");

        assertThat(second).hasSize(3);
        assertThat(second).isNotEqualTo(first.getCode());
    }
}